"""Reject automatic AI agent attribution in a pull request and its commits."""

import json
import os
import re
import subprocess
import sys


AGENT = re.compile(r"\b(?:claude|codex|copilot|chatgpt|openai|gemini)\b|anthropic\.com", re.I)
CO_AUTHOR = re.compile(r"^\s*co-authored-by:\s*(.+)$", re.I | re.M)
PR_BYLINE = re.compile(
    r"^\s*(?:🤖\s*)?generated with\s+\[?"
    r"(?:claude code|codex|github copilot|copilot|chatgpt|gemini)\b",
    re.I | re.M,
)
SESSION_LINK = re.compile(r"^\s*claude-session\s*:", re.I | re.M)


def git(*args: str) -> str:
    return subprocess.check_output(["git", *args], text=True, encoding="utf-8")


def main() -> int:
    with open(os.environ["GITHUB_EVENT_PATH"], encoding="utf-8-sig") as event_file:
        event = json.load(event_file)

    body = event["pull_request"].get("body") or ""
    errors = []
    if PR_BYLINE.search(body) or SESSION_LINK.search(body):
        errors.append("PR description contains automatic AI agent attribution")

    # On pull_request, checkout's HEAD is GitHub's test merge commit.
    # Its first parent is the base and its second parent is the PR head.
    commits = git("rev-list", "HEAD^1..HEAD^2").splitlines()
    for commit in commits:
        message = git("show", "-s", "--format=%B", commit)
        author = git("show", "-s", "--format=%an <%ae>", commit)
        co_authors = CO_AUTHOR.findall(message)
        if (
            AGENT.search(author)
            or any(AGENT.search(co_author) for co_author in co_authors)
            or SESSION_LINK.search(message)
        ):
            errors.append(f"commit {commit[:12]} contains AI agent attribution")

    for error in errors:
        print(f"::error::{error}")
    if errors:
        print("Remove the generated byline or co-author trailer, then update the PR.")
        return 1
    print("No automatic AI agent attribution found.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
