-- 사용자 행동 이벤트 원본. ERD v3 29번 events.
-- BaseCreatedEntity/BaseTimeEntity를 쓰지 않는다(occurred_at·created_at을 앱이 Clock으로 넣는다).
-- user_id에는 FK를 걸지 않는다(대량 적재·탈퇴 후에도 통계 유지). 180일 지난 원본 삭제는 집계 배치(#93)에서 한다.
CREATE TABLE events (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_name   varchar(100) NOT NULL,
    user_id      bigint,
    session_id   varchar(100),
    source       varchar(10)  NOT NULL,
    screen       varchar(100),
    properties   jsonb,
    platform     varchar(10),
    app_version  varchar(50),
    is_seed      boolean      NOT NULL DEFAULT false,
    occurred_at  timestamp    NOT NULL,
    created_at   timestamp    NOT NULL,
    CONSTRAINT ck_events_source CHECK (source IN ('CLIENT', 'SERVER'))
);

CREATE INDEX idx_events_name_occurred ON events (event_name, occurred_at);
CREATE INDEX idx_events_user_occurred ON events (user_id, occurred_at);
