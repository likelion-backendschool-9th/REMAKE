-- 계정 삭제 이메일 인증번호. ERD v4 4번 account_deletion_requests. 카카오·구글 탈퇴용.
-- 평문 번호는 넣지 않고 code_hash만 둔다. 재전송은 새 행. attempts가 5를 넘으면 그 번호는 잠긴다.

CREATE TABLE account_deletion_requests (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     bigint       NOT NULL,
    code_hash   varchar(64)  NOT NULL,
    expires_at  timestamp    NOT NULL,
    attempts    int          NOT NULL DEFAULT 0,
    verified_at timestamp,
    created_at  timestamp    NOT NULL,
    CONSTRAINT fk_account_deletion_requests_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT ck_account_deletion_requests_attempts CHECK (attempts >= 0)
);

CREATE INDEX idx_account_deletion_requests_user_id ON account_deletion_requests (user_id);
-- 하루 지난 인증번호 정리 스케줄러가 created_at으로 지운다
CREATE INDEX idx_account_deletion_requests_created_at ON account_deletion_requests (created_at);
