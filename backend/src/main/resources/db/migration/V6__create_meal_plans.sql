-- 식단표(meal_plans)와 식단 칸(meal_plan_slots). ERD v4 17·18번. 사용자 데이터라 고정 행을 넣지 않는다.
-- meal_plan_slots.recipe_id → recipes(id) FK는 recipes 테이블이 아직 없어 이 마이그레이션에 넣지 않는다.
--   recipes 테이블을 만드는 마이그레이션이 ALTER TABLE ... ON DELETE RESTRICT로 추가한다(레시피는 지우지 않음).

CREATE TABLE meal_plans (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         bigint      NOT NULL,
    start_date      date        NOT NULL,
    purpose         varchar(20) NOT NULL DEFAULT 'BALANCED',
    -- 고른 끼니를 아침·점심·저녁 순서로 콤마로 이어 저장한다(예: BREAKFAST,DINNER)
    meal_types      varchar(30) NOT NULL,
    servings        int         NOT NULL,
    -- 실제로 만든 일수. 완성(COMPLETED) 전에는 비어 있다
    generated_days  int,
    status          varchar(20) NOT NULL DEFAULT 'GENERATING',
    created_at      timestamp   NOT NULL,
    -- 생성 작업이 끝나 status·generated_days가 바뀐 시각
    updated_at      timestamp   NOT NULL,
    CONSTRAINT fk_meal_plans_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT ck_meal_plans_purpose CHECK (purpose IN ('BALANCED', 'DIET', 'HIGH_PROTEIN', 'SIMPLE', 'SAVING')),
    CONSTRAINT ck_meal_plans_meal_types CHECK (meal_types ~ '^(BREAKFAST|LUNCH|DINNER)(,(BREAKFAST|LUNCH|DINNER)){0,2}$'),
    CONSTRAINT ck_meal_plans_servings CHECK (servings >= 1),
    CONSTRAINT ck_meal_plans_generated_days CHECK (generated_days IS NULL OR generated_days BETWEEN 1 AND 7),
    CONSTRAINT ck_meal_plans_status CHECK (status IN ('GENERATING', 'COMPLETED', 'FAILED'))
);

-- 겹침 검사(API 38)·달력(API 39): 회원의 식단표를 시작일 범위로 찾는다
CREATE INDEX idx_meal_plans_user_start_date ON meal_plans (user_id, start_date);
-- 회원당 생성 중인 식단표는 하나. 같은 회원의 요청이 동시에 와도 MEAL_PLAN_IN_PROGRESS 규칙을 DB가 한 번 더 지킨다
CREATE UNIQUE INDEX uk_meal_plans_user_generating ON meal_plans (user_id) WHERE status = 'GENERATING';

CREATE TABLE meal_plan_slots (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meal_plan_id  bigint      NOT NULL,
    slot_date     date        NOT NULL,
    meal_type     varchar(20) NOT NULL,
    recipe_id     bigint      NOT NULL,
    -- 오늘 칸에서 요리를 끝낸 시각. 값이 있으면 새 식단표로 덮어써도 이 칸은 남는다
    cooked_at     timestamp,
    created_at    timestamp   NOT NULL,
    updated_at    timestamp   NOT NULL,
    CONSTRAINT fk_meal_plan_slots_meal_plan FOREIGN KEY (meal_plan_id) REFERENCES meal_plans (id) ON DELETE CASCADE,
    CONSTRAINT uk_meal_plan_slots_plan_date_meal UNIQUE (meal_plan_id, slot_date, meal_type),
    CONSTRAINT ck_meal_plan_slots_meal_type CHECK (meal_type IN ('BREAKFAST', 'LUNCH', 'DINNER'))
);

-- recipes FK가 생기면 레시피 쪽 검사에 쓰인다
CREATE INDEX idx_meal_plan_slots_recipe ON meal_plan_slots (recipe_id);
