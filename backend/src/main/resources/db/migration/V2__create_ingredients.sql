-- 냉장고 재료. ERD v3 7번 ingredients. 사용자 데이터라 고정 행을 넣지 않는다.
-- 외래 키 두 개는 참조할 테이블이 아직 없어 이 마이그레이션에 넣지 않는다.
--   user_id         → users(id)         : users 테이블을 만드는 마이그레이션이 ALTER TABLE로 추가한다.
--   receipt_item_id → receipt_items(id) : receipt_items 테이블을 만드는 마이그레이션이 ALTER TABLE ... ON DELETE SET NULL로 추가한다.
CREATE TABLE ingredients (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                 bigint        NOT NULL,
    category_id             bigint        NOT NULL,
    receipt_item_id         bigint,
    name                    varchar(50)   NOT NULL,
    storage                 varchar(10)   NOT NULL,
    expiration_date         date          NOT NULL,
    is_expiration_estimated boolean       NOT NULL DEFAULT false,
    amount                  numeric(10,3) NOT NULL,
    initial_amount          numeric(10,3) NOT NULL,
    unit                    varchar(10)   NOT NULL DEFAULT 'EA',
    price                   bigint,
    status                  varchar(10)   NOT NULL DEFAULT 'ACTIVE',
    version                 bigint        NOT NULL DEFAULT 0,
    created_at              timestamp     NOT NULL,
    updated_at              timestamp     NOT NULL,
    CONSTRAINT fk_ingredients_category FOREIGN KEY (category_id) REFERENCES ingredient_categories (id),
    CONSTRAINT uk_ingredients_receipt_item UNIQUE (receipt_item_id),
    CONSTRAINT ck_ingredients_storage CHECK (storage IN ('FRIDGE', 'FREEZER', 'PANTRY')),
    CONSTRAINT ck_ingredients_unit CHECK (unit IN ('G', 'KG', 'ML', 'L', 'EA', 'PACK', 'BUNCH', 'PIECE', 'SHEET')),
    CONSTRAINT ck_ingredients_status CHECK (status IN ('ACTIVE', 'FINISHED')),
    CONSTRAINT ck_ingredients_amount CHECK (amount >= 0 AND initial_amount > 0),
    CONSTRAINT ck_ingredients_price CHECK (price IS NULL OR price >= 0)
);

-- 사용자별 목록: ACTIVE만, 소비기한 임박순
CREATE INDEX idx_ingredients_user_status_expiration ON ingredients (user_id, status, expiration_date);
-- 알림 배치: 모든 사용자의 ACTIVE 재료를 소비기한 범위로 조회
CREATE INDEX idx_ingredients_status_expiration ON ingredients (status, expiration_date);
CREATE INDEX idx_ingredients_category ON ingredients (category_id);
