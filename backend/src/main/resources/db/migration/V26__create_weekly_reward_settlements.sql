-- 빈 주도 확정 완료로 기록한다. 순위·보상과 같은 트랜잭션에서 삽입한다.
CREATE TABLE shared_recipe_weekly_settlements (
    week_start date PRIMARY KEY,
    created_at timestamp NOT NULL
);

CREATE TABLE generation_quota_grants (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id),
    shared_recipe_id bigint REFERENCES shared_recipes(id) ON DELETE SET NULL,
    week_start date NOT NULL,
    rank_no int NOT NULL,
    amount int NOT NULL,
    remaining int NOT NULL,
    expires_at timestamp NOT NULL,
    created_at timestamp NOT NULL,
    CONSTRAINT uk_quota_grants_week_rank UNIQUE (week_start, rank_no),
    CONSTRAINT ck_quota_grants_reward CHECK (
        (rank_no = 1 AND amount = 10) OR (rank_no = 2 AND amount = 6) OR (rank_no = 3 AND amount = 3)),
    CONSTRAINT ck_quota_grants_remaining CHECK (remaining BETWEEN 0 AND amount),
    CONSTRAINT ck_quota_grants_expiry CHECK (expires_at > created_at)
);
CREATE INDEX idx_quota_grants_user_expiry ON generation_quota_grants(user_id, expires_at, id)
    WHERE remaining > 0;
ALTER TABLE usage_logs ADD CONSTRAINT fk_usage_logs_grant
    FOREIGN KEY (grant_id) REFERENCES generation_quota_grants(id) ON DELETE SET NULL;
