-- 같은 원본 레시피는 KST 월요일 시작 주에 한 번만 공유한다.
CREATE TABLE shared_recipes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id bigint NOT NULL REFERENCES recipes(id) ON DELETE RESTRICT,
    title text NOT NULL,
    image_key varchar(255) NOT NULL,
    status varchar(20) NOT NULL DEFAULT 'VISIBLE',
    created_at timestamp NOT NULL,
    updated_at timestamp NOT NULL,
    CONSTRAINT ck_shared_recipes_status CHECK (status IN ('VISIBLE', 'HIDDEN')),
    CONSTRAINT ck_shared_recipes_title CHECK (length(trim(title)) > 0)
);
-- created_at은 앱의 KST LocalDateTime이다. 추가 week 컬럼 없이 동시 요청도 DB에서 차단한다.
CREATE UNIQUE INDEX uk_shared_recipes_recipe_week
    ON shared_recipes (recipe_id, date_trunc('week', created_at));
CREATE INDEX idx_shared_recipes_status_created ON shared_recipes (status, created_at);
