-- 영수증 번호가 있는 구매의 최초 냉장고·장바구니 반영. 영수증 삭제 후에도 남아 재등록 중복 반영을 막는다(#266).
-- 보관은 구매일 기준 6개월. 재등록으로 연장하지 않고, 탈퇴 시 삭제한다.
CREATE TABLE receipt_first_applications (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         bigint NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    store_name      varchar NOT NULL,
    purchased_on    date NOT NULL,
    receipt_number  varchar NOT NULL,
    purchased_time  time,
    created_at      timestamp NOT NULL
);

CREATE UNIQUE INDEX uq_receipt_first_applications_purchase
    ON receipt_first_applications (user_id, store_name, purchased_on, receipt_number);

CREATE INDEX idx_receipt_first_applications_purchased_on
    ON receipt_first_applications (purchased_on);
