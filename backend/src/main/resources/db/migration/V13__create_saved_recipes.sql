-- ERD 15. 공유 상세의 실제 저장 여부·저장 수 조회 기반. 저장/취소 동작은 #76/#90에서 연결한다.
CREATE TABLE saved_recipes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id),
    recipe_id bigint NOT NULL REFERENCES recipes(id) ON DELETE RESTRICT,
    shared_recipe_id bigint REFERENCES shared_recipes(id) ON DELETE SET NULL,
    is_favorite boolean NOT NULL DEFAULT false,
    saved_at timestamp NOT NULL,
    CONSTRAINT uk_saved_recipes_user_recipe UNIQUE (user_id, recipe_id)
);
CREATE INDEX idx_saved_recipes_shared_saved ON saved_recipes (shared_recipe_id, saved_at);
