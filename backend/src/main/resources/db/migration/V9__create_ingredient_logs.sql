-- 재료 사용·폐기 기록. ERD v4 9번 ingredient_logs. 사용자 데이터라 고정 행을 넣지 않고, 기록은 고치지 않아 updated_at이 없다.
-- ingredient_id는 재료가 지워지면 비운다(ON DELETE SET NULL). 수량이 0이 되면 재료 행을 지우므로 기록은 이름·단위를 따로 가진다.
-- user_id는 재료가 지워진 뒤에도 월별 폐기 금액을 집계할 수 있게 둔다.
-- cost_amount는 폐기일 때만 채우고, 가격이 없으면 비운다.
CREATE TABLE ingredient_logs (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       bigint        NOT NULL,
    ingredient_id bigint,
    type          varchar(10)   NOT NULL,
    name          varchar(50)   NOT NULL,
    amount        numeric(10,3) NOT NULL,
    unit          varchar(10)   NOT NULL,
    cost_amount   bigint,
    created_at    timestamp     NOT NULL,
    CONSTRAINT fk_ingredient_logs_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_ingredient_logs_ingredient FOREIGN KEY (ingredient_id) REFERENCES ingredients (id) ON DELETE SET NULL,
    CONSTRAINT ck_ingredient_logs_type CHECK (type IN ('USED', 'DISCARDED')),
    CONSTRAINT ck_ingredient_logs_amount CHECK (amount > 0),
    CONSTRAINT ck_ingredient_logs_unit CHECK (unit IN ('G', 'KG', 'ML', 'L', 'EA', 'PACK', 'BUNCH', 'PIECE', 'SHEET')),
    CONSTRAINT ck_ingredient_logs_cost_amount CHECK (cost_amount IS NULL OR cost_amount >= 0)
);

-- 재료별 기록 확인(수량 수정 가능 여부)과 재료를 지울 때 연결 비우기
CREATE INDEX idx_ingredient_logs_ingredient ON ingredient_logs (ingredient_id);
-- 월별 폐기 금액 집계(#73)
CREATE INDEX idx_ingredient_logs_user_type_created ON ingredient_logs (user_id, type, created_at);
