-- AI 레시피(ERD v4 12~14번)와 생성 횟수 기록(16번 usage_logs). 레시피는 만든 뒤 고치지 않아 updated_at이 없다.
-- saved_recipes(15번)는 저장 API(#76)에서 만든다.
-- V6(식단표)이 recipes보다 먼저 생겨 미뤄 둔 meal_plan_slots.recipe_id FK를 맨 아래에서 추가한다(#152).

CREATE TABLE recipes (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         bigint        NOT NULL,
    source          varchar(20)   NOT NULL,
    title           varchar(100)  NOT NULL,
    servings        int           NOT NULL,
    cook_minutes    int           NOT NULL,
    tips            varchar(1000),
    -- 커스텀 생성의 선택값(인원·재료·맛·시간·도구·방식·요리 유형·알레르기). 다시 받기에 그대로 쓴다. 빠른 생성은 null.
    custom_options  jsonb,
    created_at      timestamp     NOT NULL,
    CONSTRAINT fk_recipes_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT ck_recipes_source CHECK (source IN ('QUICK', 'CUSTOM', 'MEAL_PLAN')),
    CONSTRAINT ck_recipes_servings CHECK (servings > 0),
    CONSTRAINT ck_recipes_cook_minutes CHECK (cook_minutes > 0)
);

CREATE INDEX idx_recipes_user ON recipes (user_id);

CREATE TABLE recipe_ingredients (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id       bigint        NOT NULL,
    -- 생성할 때 쓴 내 냉장고 재료(요리 완료 차감 대상). 냉장고에 없는 재료(보충)는 null, 재료를 지우면 null이 된다.
    ingredient_id   bigint,
    name            varchar(100)  NOT NULL,
    -- 비어 있으면 "약간"(TO_TASTE 등 양이 없는 단위)
    amount          numeric(10,3),
    unit            varchar(10)   NOT NULL,
    sort_order      int           NOT NULL,
    created_at      timestamp     NOT NULL,
    CONSTRAINT fk_recipe_ingredients_recipe FOREIGN KEY (recipe_id) REFERENCES recipes (id) ON DELETE CASCADE,
    CONSTRAINT fk_recipe_ingredients_ingredient FOREIGN KEY (ingredient_id) REFERENCES ingredients (id) ON DELETE SET NULL,
    CONSTRAINT ck_recipe_ingredients_unit CHECK (unit IN (
        'G', 'KG', 'ML', 'L', 'TBSP', 'TSP', 'CUP', 'EA', 'PACK', 'BUNCH', 'PIECE', 'SHEET', 'PINCH', 'TO_TASTE')),
    CONSTRAINT ck_recipe_ingredients_amount CHECK (amount IS NULL OR amount > 0),
    CONSTRAINT ck_recipe_ingredients_sort_order CHECK (sort_order >= 0)
);

CREATE INDEX idx_recipe_ingredients_recipe ON recipe_ingredients (recipe_id, sort_order);
-- 재료 삭제 때 SET NULL 대상을 찾는 데 쓴다.
CREATE INDEX idx_recipe_ingredients_ingredient ON recipe_ingredients (ingredient_id);

CREATE TABLE recipe_steps (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id       bigint        NOT NULL,
    step_no         int           NOT NULL,
    content         varchar(1000) NOT NULL,
    created_at      timestamp     NOT NULL,
    CONSTRAINT fk_recipe_steps_recipe FOREIGN KEY (recipe_id) REFERENCES recipes (id) ON DELETE CASCADE,
    CONSTRAINT uk_recipe_steps_recipe_step_no UNIQUE (recipe_id, step_no),
    CONSTRAINT ck_recipe_steps_step_no CHECK (step_no >= 1)
);

-- 성공한 생성만 한 행. 남은 횟수는 이 표를 세어 계산한다(실패는 넣지 않음 = 차감 없음).
-- grant_id → generation_quota_grants(id) ON DELETE SET NULL 외래 키는 그 테이블(공유·장바구니 영역)을 만드는 마이그레이션이 ALTER TABLE로 추가한다.
CREATE TABLE usage_logs (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         bigint        NOT NULL,
    type            varchar(20)   NOT NULL,
    grant_id        bigint,
    created_at      timestamp     NOT NULL,
    CONSTRAINT fk_usage_logs_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT ck_usage_logs_type CHECK (type IN ('RECIPE', 'MEAL_PLAN'))
);

-- 오늘(레시피)·이번 달(식단표) 사용 횟수 조회
CREATE INDEX idx_usage_logs_user_type_created ON usage_logs (user_id, type, created_at);

-- 식단 칸의 레시피(ERD 관계 표 recipes → meal_plan_slots, RESTRICT: 레시피는 지우지 않음). 인덱스는 V6의 idx_meal_plan_slots_recipe.
ALTER TABLE meal_plan_slots
    ADD CONSTRAINT fk_meal_plan_slots_recipe FOREIGN KEY (recipe_id) REFERENCES recipes (id) ON DELETE RESTRICT;
