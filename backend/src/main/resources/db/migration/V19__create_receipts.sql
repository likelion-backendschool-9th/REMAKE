CREATE TABLE receipts (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      bigint NOT NULL REFERENCES users (id),
    purchased_on date NOT NULL,
    purchased_time time,
    receipt_number varchar,
    store_name   varchar NOT NULL,
    store_code   varchar,
    image_key    varchar NOT NULL,
    created_at   timestamp NOT NULL
);

CREATE INDEX idx_receipts_user_purchased ON receipts (user_id, purchased_on);
CREATE INDEX idx_receipts_user_store_number ON receipts (user_id, store_name, receipt_number);

CREATE TABLE receipt_items (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_id              bigint NOT NULL REFERENCES receipts (id) ON DELETE CASCADE,
    category_id             bigint NOT NULL REFERENCES ingredient_categories (id),
    name                    varchar NOT NULL,
    amount                  numeric(10,3) NOT NULL DEFAULT 1 CHECK (amount > 0),
    unit                    varchar NOT NULL DEFAULT 'EA',
    price                   bigint CHECK (price >= 0),
    storage                 varchar NOT NULL,
    created_at              timestamp NOT NULL
);

CREATE INDEX idx_receipt_items_receipt ON receipt_items (receipt_id);

