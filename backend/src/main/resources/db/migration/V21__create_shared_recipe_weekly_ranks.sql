-- ERD 22. #88은 지난주 기록을 조회하고, 확정 순위 기록·보상 지급은 #92에서 구현한다.
CREATE TABLE shared_recipe_weekly_ranks (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    week_start date NOT NULL,
    shared_recipe_id bigint NOT NULL REFERENCES shared_recipes(id) ON DELETE CASCADE,
    rank_no int NOT NULL,
    save_count int NOT NULL,
    created_at timestamp NOT NULL,
    CONSTRAINT uk_shared_recipe_weekly_ranks_week_recipe UNIQUE (week_start, shared_recipe_id),
    CONSTRAINT ck_shared_recipe_weekly_ranks_rank CHECK (rank_no BETWEEN 1 AND 100),
    CONSTRAINT ck_shared_recipe_weekly_ranks_saves CHECK (save_count >= 0)
);
