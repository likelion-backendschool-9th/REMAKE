-- 재료 카테고리(기준 데이터). ERD v3 5번 ingredient_categories.
-- 기준 데이터는 마이그레이션으로만 넣는다. 머지된 뒤 값을 바꿀 때는 이 파일을 고치지 않고 새 번호의 마이그레이션을 추가한다.
-- 값 출처: 기본 소비기한 일수는 PRD 부록 B 초안. 기본 보관 위치·기본 단위·이미지 경로는 정해진 값이 없어 임시로 넣었다.
-- 기본 단위는 냉장고 담당과 정한 뒤 새 번호의 마이그레이션으로 고친다(이미지는 파일이 정해지기 전까지 프론트가 기본 이미지로 대체).
CREATE TABLE ingredient_categories (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                    varchar(30)  NOT NULL UNIQUE,
    name                    varchar(30)  NOT NULL,
    image_url               varchar(500) NOT NULL,
    default_storage         varchar(10)  NOT NULL,
    default_unit            varchar(10)  NOT NULL,
    default_shelf_life_days int          NOT NULL,
    -- enum(StorageLocation, IngredientUnit)에 없는 값은 JPA가 읽을 때 오류가 나므로 DB에서도 막는다.
    CONSTRAINT ck_ingredient_categories_default_storage
        CHECK (default_storage IN ('FRIDGE', 'FREEZER', 'PANTRY')),
    CONSTRAINT ck_ingredient_categories_default_unit
        CHECK (default_unit IN ('G', 'KG', 'ML', 'L', 'EA', 'PACK', 'BUNCH', 'PIECE', 'SHEET')),
    CONSTRAINT ck_ingredient_categories_default_shelf_life_days
        CHECK (default_shelf_life_days > 0)
);

