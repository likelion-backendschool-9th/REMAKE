-- 소셜 로그인 회원(users)과 리프레시 토큰(refresh_tokens).
-- users.provider_user_id는 탈퇴 시 null. PostgreSQL은 null끼리 중복으로 보지 않아 같은 소셜 계정으로 재가입할 수 있다.
-- ingredients.user_id FK는 users가 생긴 뒤 여기서 건다(V2 주석).

CREATE TABLE users (
    id                          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider                    varchar(20)  NOT NULL,
    provider_user_id            varchar(255),
    email                       varchar(320),
    role                        varchar(20)  NOT NULL DEFAULT 'USER',
    status                      varchar(20)  NOT NULL DEFAULT 'ACTIVE',
    plan                        varchar(20)  NOT NULL DEFAULT 'BASIC',
    household_size              int,
    onboarding_completed        boolean      NOT NULL DEFAULT false,
    recipe_supplement_enabled   boolean      NOT NULL DEFAULT false,
    notification_enabled        boolean      NOT NULL DEFAULT true,
    last_meal_purpose           varchar(50),
    created_at                  timestamp    NOT NULL,
    updated_at                  timestamp    NOT NULL,
    deleted_at                  timestamp,
    CONSTRAINT uq_users_provider_provider_user_id UNIQUE (provider, provider_user_id)
);

CREATE TABLE refresh_tokens (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     bigint       NOT NULL,
    token_hash  varchar(64)  NOT NULL,
    expires_at  timestamp    NOT NULL,
    revoked_at  timestamp,
    created_at  timestamp    NOT NULL,
    CONSTRAINT uq_refresh_tokens_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_refresh_tokens_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE INDEX idx_refresh_tokens_user_id ON refresh_tokens (user_id);

-- users 없이 넣었던 개발 leftover ingredients는 FK를 걸 수 없어 제거한다.
-- 주의: users는 바로 위에서 새로 만들어 이 시점에 비어 있으므로, 이 문장은 ingredients를 **전부** 지운다.
-- ingredients가 0행이면 영향 없음. 적용 전 서버의 ingredients 건수를 확인하고, 남아 있으면 팀 동의 후 적용한다.
DELETE FROM ingredients
WHERE NOT EXISTS (SELECT 1 FROM users u WHERE u.id = ingredients.user_id);

ALTER TABLE ingredients
    ADD CONSTRAINT fk_ingredients_user FOREIGN KEY (user_id) REFERENCES users (id);
