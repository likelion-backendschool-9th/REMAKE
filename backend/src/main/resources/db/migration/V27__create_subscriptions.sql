-- 구독·결제 기록. ERD v4 5·6번. 미종료 구독(ACTIVE|CANCELED)은 회원당 하나.

CREATE TABLE subscriptions (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id              bigint       NOT NULL,
    status               varchar(20)  NOT NULL,
    customer_key         varchar(100) NOT NULL,
    billing_key          varchar(512),
    price                bigint       NOT NULL DEFAULT 9900,
    current_period_start date         NOT NULL,
    next_billing_date    date         NOT NULL,
    canceled_at          timestamp,
    ended_at             timestamp,
    created_at           timestamp    NOT NULL,
    updated_at           timestamp    NOT NULL,
    CONSTRAINT fk_subscriptions_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT uk_subscriptions_customer_key UNIQUE (customer_key),
    CONSTRAINT ck_subscriptions_status CHECK (status IN ('ACTIVE', 'CANCELED', 'ENDED')),
    CONSTRAINT ck_subscriptions_price CHECK (price > 0)
);

CREATE UNIQUE INDEX uk_subscriptions_user_unfinished
    ON subscriptions (user_id)
    WHERE status IN ('ACTIVE', 'CANCELED');

CREATE INDEX idx_subscriptions_next_billing_date
    ON subscriptions (next_billing_date)
    WHERE status IN ('ACTIVE', 'CANCELED');

CREATE TABLE subscription_payments (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscription_id bigint       NOT NULL,
    user_id         bigint       NOT NULL,
    order_id        varchar(64)  NOT NULL,
    payment_key     varchar(200),
    amount          bigint       NOT NULL,
    status          varchar(20)  NOT NULL,
    failure_code    varchar(64),
    period_start    date         NOT NULL,
    period_end      date         NOT NULL,
    approved_at     timestamp,
    created_at      timestamp    NOT NULL,
    CONSTRAINT fk_subscription_payments_subscription
        FOREIGN KEY (subscription_id) REFERENCES subscriptions (id) ON DELETE RESTRICT,
    CONSTRAINT fk_subscription_payments_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT uk_subscription_payments_order_id UNIQUE (order_id),
    CONSTRAINT ck_subscription_payments_status CHECK (status IN ('DONE', 'FAILED')),
    CONSTRAINT ck_subscription_payments_amount CHECK (amount > 0)
);

CREATE INDEX idx_subscription_payments_user_id ON subscription_payments (user_id);
CREATE INDEX idx_subscription_payments_subscription_id ON subscription_payments (subscription_id);
