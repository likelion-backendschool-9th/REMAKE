CREATE TABLE shared_recipe_reports (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shared_recipe_id bigint NOT NULL REFERENCES shared_recipes(id) ON DELETE CASCADE,
    reporter_id bigint NOT NULL REFERENCES users(id),
    reason varchar(30) NOT NULL,
    status varchar(20) NOT NULL DEFAULT 'PENDING',
    created_at timestamp NOT NULL,
    CONSTRAINT uk_shared_recipe_reports_reporter_post UNIQUE (reporter_id, shared_recipe_id),
    CONSTRAINT ck_shared_recipe_reports_reason CHECK (reason IN ('OFFENSIVE_IMAGE', 'AD_TITLE', 'DANGEROUS_RECIPE', 'OTHER')),
    CONSTRAINT ck_shared_recipe_reports_status CHECK (status IN ('PENDING', 'DONE'))
);
CREATE INDEX idx_shared_recipe_reports_post ON shared_recipe_reports (shared_recipe_id);
