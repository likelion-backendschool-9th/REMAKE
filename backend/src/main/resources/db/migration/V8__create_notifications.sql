-- 앱 안 알림(notifications). ERD v4 24번. 기기 푸시 테이블은 없다.
-- 재실행 중복은 임박(재료·하루)·기한 지남(회원·하루) 유니크 인덱스로 막는다.

CREATE TABLE notifications (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         bigint       NOT NULL,
    type            varchar(30)  NOT NULL,
    ingredient_id   bigint,
    meal_plan_id    bigint,
    message         varchar(500) NOT NULL,
    read_at         timestamp,
    created_at      timestamp    NOT NULL,
    CONSTRAINT fk_notifications_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_notifications_ingredient FOREIGN KEY (ingredient_id) REFERENCES ingredients (id) ON DELETE SET NULL,
    CONSTRAINT fk_notifications_meal_plan FOREIGN KEY (meal_plan_id) REFERENCES meal_plans (id) ON DELETE SET NULL,
    CONSTRAINT ck_notifications_type CHECK (type IN (
        'EXPIRY_SOON', 'EXPIRED', 'MEAL_PLAN_COMPLETED', 'MEAL_PLAN_FAILED'
    ))
);

CREATE INDEX idx_notifications_user_created ON notifications (user_id, created_at DESC);
CREATE INDEX idx_notifications_user_unread ON notifications (user_id) WHERE read_at IS NULL;

-- 같은 날 같은 재료의 임박 알림은 한 건만 (배치 재실행 대비)
CREATE UNIQUE INDEX uk_notifications_expiry_soon_daily
    ON notifications (user_id, ingredient_id, ((created_at)::date))
    WHERE type = 'EXPIRY_SOON' AND ingredient_id IS NOT NULL;

-- 같은 날 기한 지남 알림은 회원당 한 건만
CREATE UNIQUE INDEX uk_notifications_expired_daily
    ON notifications (user_id, ((created_at)::date))
    WHERE type = 'EXPIRED';
