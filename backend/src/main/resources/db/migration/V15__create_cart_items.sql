-- #89 장바구니 기반과 #57 영수증 선택 차감. 사용자 입력 수량은 numeric(10,3) 범위이다.
-- 배정 삭제와 장바구니는 독립적이다. 슬롯은 최초 담기 출처이며 삭제되면 연결만 비운다.
CREATE TABLE cart_items (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           bigint        NOT NULL,
    recipe_id         bigint,
    meal_plan_slot_id bigint,
    category_id       bigint        NOT NULL,
    name              varchar(50)   NOT NULL,
    amount            numeric(10,3) NOT NULL,
    unit              varchar(10)   NOT NULL,
    created_at        timestamp     NOT NULL,
    updated_at        timestamp     NOT NULL,
    CONSTRAINT fk_cart_items_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_cart_items_recipe FOREIGN KEY (recipe_id) REFERENCES recipes (id) ON DELETE SET NULL,
    CONSTRAINT fk_cart_items_slot FOREIGN KEY (meal_plan_slot_id) REFERENCES meal_plan_slots (id) ON DELETE SET NULL,
    CONSTRAINT fk_cart_items_category FOREIGN KEY (category_id) REFERENCES ingredient_categories (id) ON DELETE RESTRICT,
    CONSTRAINT ck_cart_items_amount CHECK (amount > 0)
);

CREATE INDEX idx_cart_items_user ON cart_items (user_id, id);
CREATE INDEX idx_cart_items_recipe ON cart_items (recipe_id);
CREATE INDEX idx_cart_items_slot ON cart_items (meal_plan_slot_id);
