-- 재료 사전(기준 데이터). ERD v3 6번 ingredient_catalog. 재료 이름 자동완성, 온보딩 제외 재료(user_excluded_ingredients),
-- 영수증 품목 정규화가 같은 목록을 쓴다. 기준 데이터는 마이그레이션으로만 넣고, 머지된 뒤 값을 바꿀 때는 이 파일을 고치지 않고 새 번호의 마이그레이션을 추가한다.
-- 값 출처: 이름·소비기한 일수는 일반 식재료 기준 초안이다(소비기한 세부는 개발자에게 위임된 값). shelf_life_days가 NULL이면 카테고리 기본값을 쓴다.
-- is_common_exclusion은 식품 알레르기 유발 표시 대상 식품(식약처) 가운데 대표 항목이다. 온보딩 알레르기 화면의 상단 목록이 된다.
-- 갑각류·조개류처럼 묶음 이름도 넣어 레시피의 알레르기 경고(recipe_catalog_items)가 묶음 단위로 맞출 수 있게 한다.
CREATE TABLE ingredient_catalog (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id         bigint      NOT NULL REFERENCES ingredient_categories (id),
    name                varchar(50) NOT NULL UNIQUE,
    shelf_life_days     int,
    is_common_exclusion boolean     NOT NULL DEFAULT false,
    CONSTRAINT ck_ingredient_catalog_shelf_life_days
        CHECK (shelf_life_days IS NULL OR shelf_life_days > 0)
);

CREATE INDEX idx_ingredient_catalog_category_id ON ingredient_catalog (category_id);

